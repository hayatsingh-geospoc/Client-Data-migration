-- Creates the per-dataset partitions (e.g. core.person_records_d3) of every partitioned core table.
-- To reload one dataset: unlink its people/companies, then DROP its partitions and re-run this.
CREATE FUNCTION catalog.create_dataset_partitions(p_dataset_id smallint) RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['company_records', 'person_records', 'record_emails', 'record_phones',
                             'record_profiles', 'email_verifications', 'company_record_categories',
                             'company_record_technologies', 'company_funding']
    LOOP
        EXECUTE format('CREATE TABLE IF NOT EXISTS core.%I PARTITION OF core.%I FOR VALUES IN (%s)',
                       t || '_d' || p_dataset_id, t, p_dataset_id);
    END LOOP;
END;
$$;

-- Removes ONE dataset's source records (all its partitions) so it can be re-imported; other datasets are
-- untouched. Order matters: tables that reference others go first; referenced partitions are detached before
-- dropping. Canonical people/companies are kept; re-run matching afterwards to refresh their values.
CREATE FUNCTION catalog.drop_dataset_partitions(p_dataset_id smallint) RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['email_verifications', 'company_record_categories', 'company_record_technologies',
                             'company_funding', 'record_phones', 'record_profiles', 'record_emails',
                             'person_records', 'company_records']
    LOOP
        IF to_regclass(format('core.%I', t || '_d' || p_dataset_id)) IS NOT NULL THEN
            EXECUTE format('ALTER TABLE core.%I DETACH PARTITION core.%I', t, t || '_d' || p_dataset_id);
            EXECUTE format('DROP TABLE core.%I', t || '_d' || p_dataset_id);
        END IF;
    END LOOP;
END;
$$;

-- -----------------------------------------------------------------------------
-- core: deduplication decisions (nothing is merged silently)
-- -----------------------------------------------------------------------------

CREATE TABLE core.match_candidates (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity              text NOT NULL CHECK (entity IN ('person', 'company')),
    left_dataset_id     smallint NOT NULL,
    left_record_id      bigint NOT NULL,
    right_dataset_id    smallint NOT NULL,
    right_record_id     bigint NOT NULL,
    rule                text NOT NULL,          -- 'email', 'linkedin_url', 'domain', 'name_location', ...
    score               numeric(5, 4) NOT NULL CHECK (score BETWEEN 0 AND 1),
    status              text NOT NULL DEFAULT 'needs_review'
                        CHECK (status IN ('auto_merged', 'needs_review', 'confirmed', 'rejected')),
    decided_by          text,
    decided_at          timestamptz,
    note                text,
    created_at          timestamptz NOT NULL DEFAULT now(),
    CHECK ((left_dataset_id, left_record_id) < (right_dataset_id, right_record_id)),
    UNIQUE (entity, left_dataset_id, left_record_id, right_dataset_id, right_record_id, rule)
);
