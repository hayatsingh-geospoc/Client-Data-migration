-- =============================================================================
-- Leads database schema — DRAFT v0.2 (decisions of 2026-10-31 applied; not applied to any server yet)
--
-- Decisions:
--   * Cleaned data only in the database. No raw-row layer: each record carries a provenance pointer
--     (file + sheet + row_number) back to the original ZIPs, which stay on Google Drive as the raw archive.
--     Columns without a canonical field are kept in `extra` (jsonb); rows that cannot be parsed are kept in
--     catalog.rejected_rows. Nothing is dropped silently.
--   * Survivorship: dataset priority wins (1 = best). Priority is assigned by how recent each dataset is
--     (config/datasets.csv, from dates in file names / ZIP file times / row dates); newest dataset = 1.
--   * Exact duplicate files (incl. Shopify folder = WooCommerce folder, PDL JSON = PDL CSV) are loaded once.
--
-- Two PostgreSQL schemas:
--   catalog : provenance and import bookkeeping
--   core    : cleaned data — source-level records (partitioned by dataset) + canonical deduplicated entities
--
-- PostgreSQL 14+, no extensions. Secondary indexes: indexes.sql (create after bulk load).
-- See docs/schema_design.md and docs/erd.md.
-- =============================================================================

CREATE SCHEMA IF NOT EXISTS catalog;
CREATE SCHEMA IF NOT EXISTS core;

-- -----------------------------------------------------------------------------
-- catalog
-- -----------------------------------------------------------------------------

-- One row per client data product, e.g. "Entire Apollo Database".
CREATE TABLE catalog.datasets (
    id              smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            text NOT NULL UNIQUE,
    vendor          text,
    dataset_kind    text NOT NULL DEFAULT 'person' CHECK (dataset_kind IN ('person', 'company', 'mixed')),
    data_as_of      date,                       -- best known date of the data (see config/datasets.csv)
    priority        smallint NOT NULL DEFAULT 100,  -- survivorship rank: 1 = newest dataset = wins conflicts
    notes           text,
    created_at      timestamptz NOT NULL DEFAULT now()
);

-- A ZIP archive; nested archives point to their parent.
CREATE TABLE catalog.archives (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id          smallint NOT NULL REFERENCES catalog.datasets (id),
    parent_archive_id   integer REFERENCES catalog.archives (id),
    path                text NOT NULL,
    drive_file_id       text,
    size_bytes          bigint,
    source_modified_at  timestamptz,
    UNIQUE (parent_archive_id, path)
);

-- A distinct header layout shared by many files.
CREATE TABLE catalog.layouts (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fingerprint     text NOT NULL UNIQUE,
    headers         text[] NOT NULL,
    has_header_row  boolean NOT NULL DEFAULT true,
    dataset_kind    text CHECK (dataset_kind IN ('person', 'company', 'mixed')),
    notes           text
);

CREATE TABLE catalog.files (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    archive_id          integer NOT NULL REFERENCES catalog.archives (id),
    member_path         text NOT NULL,
    file_kind           text NOT NULL CHECK (file_kind IN ('csv', 'xlsx', 'ndjson', 'json', 'txt', 'other')),
    size_bytes          bigint,
    crc32               char(8),
    layout_id           integer REFERENCES catalog.layouts (id),
    encoding            text,
    delimiter           text,
    data_as_of          date,                   -- e.g. from file name "Pitchbook 2025-09-14"
    estimated_rows      bigint,
    exact_rows          bigint,
    duplicate_of_file_id integer REFERENCES catalog.files (id),   -- exact copy: loaded once, provenance kept
    load_status         text NOT NULL DEFAULT 'pending'
                        CHECK (load_status IN ('pending', 'loading', 'loaded', 'failed',
                                               'skipped_duplicate', 'skipped_empty', 'skipped_non_data')),
    skip_reason         text,
    UNIQUE (archive_id, member_path)
);

-- Reviewed column -> canonical target mapping (generated from reports/column_mapping.csv).
CREATE TABLE catalog.column_mappings (
    layout_id       integer NOT NULL REFERENCES catalog.layouts (id),
    column_index    smallint NOT NULL,
    source_header   text NOT NULL,
    target          text,                       -- 'person.email', ...; NULL = goes to extra
    transform       text,                       -- 'float_to_digits', 'split_list', 'email_with_status', ...
    review_status   text NOT NULL DEFAULT 'proposed' CHECK (review_status IN ('proposed', 'approved', 'rejected')),
    review_note     text,
    PRIMARY KEY (layout_id, column_index)
);

CREATE TABLE catalog.import_batches (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_id             integer NOT NULL REFERENCES catalog.files (id),
    pipeline_version    text NOT NULL,
    status              text NOT NULL DEFAULT 'running'
                        CHECK (status IN ('running', 'succeeded', 'failed', 'cancelled')),
    started_at          timestamptz NOT NULL DEFAULT now(),
    finished_at         timestamptz,
    rows_read           bigint NOT NULL DEFAULT 0,
    rows_inserted       bigint NOT NULL DEFAULT 0,
    rows_already_present bigint NOT NULL DEFAULT 0,
    rows_rejected       bigint NOT NULL DEFAULT 0,
    last_row_committed  bigint NOT NULL DEFAULT 0,  -- resume point
    error_message       text
);

-- Rows that could not be parsed or mapped at all (wrong column count, broken quoting). Original text kept.
CREATE TABLE catalog.rejected_rows (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id      smallint NOT NULL REFERENCES catalog.datasets (id),
    file_id         integer NOT NULL REFERENCES catalog.files (id),
    sheet_name      text NOT NULL DEFAULT '',
    row_number      bigint NOT NULL,
    import_batch_id bigint NOT NULL REFERENCES catalog.import_batches (id),
    reason          text NOT NULL,              -- 'width_mismatch', 'unparseable', ...
    raw_line        text NOT NULL,
    UNIQUE (file_id, sheet_name, row_number)
);

-- Single values that failed conversion (bad date/number/email). The record is still loaded with NULL there.
CREATE TABLE catalog.transform_errors (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id      smallint NOT NULL,
    file_id         integer NOT NULL,
    sheet_name      text NOT NULL DEFAULT '',
    row_number      bigint NOT NULL,
    import_batch_id bigint NOT NULL REFERENCES catalog.import_batches (id),
    target          text NOT NULL,
    bad_value       text,
    error           text NOT NULL
);

-- -----------------------------------------------------------------------------
-- core: lookup tables (each distinct value stored once)
-- -----------------------------------------------------------------------------

CREATE TABLE core.locations (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_code    char(2),
    country         text,
    state           text,
    city            text,
    postal_code     text,
    norm_key        text NOT NULL UNIQUE        -- normalized "country|state|city|postal"
);

CREATE TABLE core.email_addresses (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           text NOT NULL UNIQUE CHECK (email = lower(email)),
    domain          text NOT NULL,
    is_free_provider boolean
);

CREATE TABLE core.phone_numbers (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone           text NOT NULL UNIQUE,       -- E.164 when parseable, else digits only
    is_e164         boolean NOT NULL DEFAULT false,
    country_code    char(2)
);

CREATE TABLE core.profile_urls (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    platform        text NOT NULL CHECK (platform IN ('linkedin', 'twitter', 'facebook', 'github', 'instagram',
                                                      'youtube', 'tiktok', 'pinterest', 'crunchbase',
                                                      'clutch', 'pitchbook', 'other')),
    url             text NOT NULL,              -- normalized
    username        text,
    UNIQUE (platform, url)
);

CREATE TABLE core.categories (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            text NOT NULL,
    normalized_name text NOT NULL UNIQUE
);

CREATE TABLE core.technologies (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            text NOT NULL,
    normalized_name text NOT NULL UNIQUE
);

-- -----------------------------------------------------------------------------
-- core: canonical entities (one row per real-world company / person after matching)
-- Values come from the linked source record whose dataset has the best priority (ties: newest observed_at).
-- -----------------------------------------------------------------------------

CREATE TABLE core.companies (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            text,
    normalized_name text,
    domain          text,
    linkedin_url    text,
    industry        text,
    employee_range  text,
    employee_count  integer,
    revenue_usd     numeric(18, 2),
    founded_year    smallint CHECK (founded_year BETWEEN 1600 AND 2100),
    description     text,
    location_id     bigint REFERENCES core.locations (id),
    record_count    integer NOT NULL DEFAULT 0,
    last_observed_at timestamptz,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE core.people (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name       text,
    first_name      text,
    middle_name     text,
    last_name       text,
    job_title       text,
    company_id      bigint REFERENCES core.companies (id),
    location_id     bigint REFERENCES core.locations (id),
    record_count    integer NOT NULL DEFAULT 0,
    last_observed_at timestamptz,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now()
);

-- -----------------------------------------------------------------------------
-- core: source-level records, partitioned by dataset so one source can be reloaded or dropped alone.
-- Each source row yields at most one company record and one person record. Conflicting values between
-- sources are preserved here; canonical tables hold the winning value.
-- Provenance columns (dataset_id, file_id, sheet_name, row_number) point back to the original file row.
-- -----------------------------------------------------------------------------

CREATE TABLE core.company_records (
    dataset_id      smallint NOT NULL REFERENCES catalog.datasets (id),
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    file_id         integer NOT NULL REFERENCES catalog.files (id),
    sheet_name      text NOT NULL DEFAULT '',
    row_number      bigint NOT NULL,            -- 1-based data row in the file (header excluded)
    import_batch_id bigint NOT NULL REFERENCES catalog.import_batches (id),
    row_hash        bytea,                      -- md5 of the source row: exact-row duplicates across files
    company_id      bigint REFERENCES core.companies (id),   -- set by matching
    name            text,
    normalized_name text,
    website_raw     text,
    domain          text,
    linkedin_url    text,
    industry        text,
    sub_industry    text,
    employee_count  integer,
    employee_range  text,
    revenue_raw     text,
    revenue_usd     numeric(18, 2),
    founded_year    smallint CHECK (founded_year BETWEEN 1600 AND 2100),
    description     text,
    logo_url        text,
    location_id     bigint REFERENCES core.locations (id),
    location_raw    text,
    address         text,
    extra           jsonb,                      -- every source column without a canonical field, by header
    observed_at     timestamptz,                -- row date if the source has one; tie-breaker
    observed_at_source text NOT NULL DEFAULT 'unknown'
                    CHECK (observed_at_source IN ('row', 'file', 'dataset', 'unknown')),
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (dataset_id, id),
    UNIQUE (dataset_id, file_id, sheet_name, row_number)    -- idempotent re-imports
) PARTITION BY LIST (dataset_id);

CREATE TABLE core.person_records (
    dataset_id      smallint NOT NULL REFERENCES catalog.datasets (id),
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    file_id         integer NOT NULL REFERENCES catalog.files (id),
    sheet_name      text NOT NULL DEFAULT '',
    row_number      bigint NOT NULL,
    import_batch_id bigint NOT NULL REFERENCES catalog.import_batches (id),
    row_hash        bytea,
    person_id       bigint REFERENCES core.people (id),      -- set by matching
    company_record_id bigint,                                -- employer stated in the same source row
    full_name       text,
    first_name      text,
    middle_name     text,
    last_name       text,
    job_title       text,
    job_title_normalized text,
    seniority       text,
    department      text,
    job_start_date  date,
    headline        text,
    skills          text,
    gender          text,
    birth_date_raw  text,
    linkedin_connections integer,
    location_id     bigint REFERENCES core.locations (id),
    location_raw    text,
    address         text,
    extra           jsonb,
    observed_at     timestamptz,
    observed_at_source text NOT NULL DEFAULT 'unknown'
                    CHECK (observed_at_source IN ('row', 'file', 'dataset', 'unknown')),
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (dataset_id, id),
    UNIQUE (dataset_id, file_id, sheet_name, row_number),
    FOREIGN KEY (dataset_id, company_record_id) REFERENCES core.company_records (dataset_id, id)
) PARTITION BY LIST (dataset_id);

-- Contact points. Each link belongs to exactly one person record or one company record (same dataset).
CREATE TABLE core.record_emails (
    dataset_id          smallint NOT NULL,
    id                  bigint GENERATED BY DEFAULT AS IDENTITY,
    person_record_id    bigint,
    company_record_id   bigint,
    email_address_id    bigint NOT NULL REFERENCES core.email_addresses (id),
    email_raw           text NOT NULL,
    email_kind          text NOT NULL DEFAULT 'unknown'
                        CHECK (email_kind IN ('work', 'direct', 'personal', 'generic', 'unknown')),
    position            smallint NOT NULL DEFAULT 1,
    source_status       text,                   -- e.g. 'Verified', 'Accept_all'
    source_column       text NOT NULL,
    PRIMARY KEY (dataset_id, id),
    FOREIGN KEY (dataset_id, person_record_id) REFERENCES core.person_records (dataset_id, id),
    FOREIGN KEY (dataset_id, company_record_id) REFERENCES core.company_records (dataset_id, id),
    CHECK ((person_record_id IS NULL) <> (company_record_id IS NULL))
) PARTITION BY LIST (dataset_id);

